import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ExcelJS from 'exceljs';
import {readTable,autoMapping,mapRows,validateImport,LIMITS} from '../web/lib/import.js';
const bytes=s=>new TextEncoder().encode(s);
const readExample=async name=>readTable(await readFile(new URL('../examples/'+name,import.meta.url)),{name});
const mapped=async(name,kind)=>{const file=await readExample(name);return mapRows(file.sheets[0],autoMapping(file.sheets[0].headers,kind),{kind,sourceName:name,sourceId:file.sourceId});};

test('CSV Unicode/BOM, quotes, multiline, decimal commas and source line numbers',async()=>{
 const source='\uFEFFID;Поставщик;Наименование;Цена;Единица цены;Заметка\r\nA;"ДЕМО; Альфа";"Крепёж\r\nM6";"1,234";шт;"сказал ""да"""\r\n';
 const table=await readTable(bytes(source),{name:'price.csv'});const sheet=table.sheets[0];
 assert.equal(sheet.rows[0].Цена,'1,234');assert.equal(sheet.rows[0].Заметка,'сказал "да"');
 const rows=mapRows(sheet,autoMapping(sheet.headers,'offers'),{kind:'offers',sourceName:'price.csv',sourceId:table.sourceId});
 assert.equal(rows[0].supplier,'ДЕМО; Альфа');assert.equal(rows[0].name,'Крепёж\r\nM6');assert.equal(rows[0]._source.row,2);assert.equal(rows[0]._source.original.Заметка,'сказал "да"');
 rows[0].name='исправлено';assert.equal(rows[0]._source.original.Наименование,'Крепёж\r\nM6');
});
