test('blank input, invalid encoding, unsupported extension and input limits',async()=>{
 await assert.rejects(readTable(bytes(''),{name:'p.csv'}),/пуст/);
 await assert.rejects(readTable(new Uint8Array([255,254,0]),{name:'p.csv'}),/UTF-8/);
 await assert.rejects(readTable(bytes('abc'),{name:'p.xls'}),/XLS/);
 await assert.rejects(readTable(new Uint8Array(LIMITS.bytes+1),{name:'p.csv'}),/5 МБ/);
 await assert.rejects(readTable(bytes('id\n'+Array.from({length:5001},(_,i)=>i).join('\n')),{name:'p.csv'}),/5000/);
});
