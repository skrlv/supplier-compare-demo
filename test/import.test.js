test('ambiguous or broken headers, malformed quotes and wrong widths reject',async()=>{
 for(const s of ['id;id\nA;B',';name\nA;B','id;name\nA;B;C','id;name\nA;"broken','id;name\nA;"closed"wrong','id;name\nA;bro"ken'])await assert.rejects(readTable(bytes(s),{name:'p.csv'}));
 assert.throws(()=>autoMapping(['name','Наименование'],'catalog'),/одно поле/);
 const file=await readTable(bytes('name;base_unit;required_qty\nДЕМО;шт;1'),{name:'p.csv'});
 assert.throws(()=>mapRows(file.sheets[0],{name:'name',base_unit:'name',required_qty:'required_qty'},{kind:'catalog',sourceId:file.sourceId}),/нескольким/);
});
test('stable scoped autogenerated IDs; source, sheet, original, mapping retained',async()=>{
 const file=await readTable(bytes('name;base_unit;required_qty\nДЕМО;шт;1'),{name:'catalog.csv'});
 const options={kind:'catalog',sourceName:'catalog.csv',sourceId:file.sourceId};
 const one=mapRows(file.sheets[0],autoMapping(file.sheets[0].headers,'catalog'),options);
 const two=mapRows(file.sheets[0],autoMapping(file.sheets[0].headers,'catalog'),options);
 assert.equal(one[0].id,two[0].id);assert.equal(one[0]._source.file,'catalog.csv');assert.equal(one[0]._source.sheet,'Таблица');assert.deepEqual(one[0]._source.mapping,{name:'name',base_unit:'base_unit',required_qty:'required_qty'});
 assert.throws(()=>validateImport(one,two,'catalog'),/уже импортирован/);
});
test('XLSX real two-sheet fixture, text SKUs, formula, errors, dates and corruption',async()=>{
 const file=await readExample('offers.xlsx');assert.equal(file.sheets.length,2);assert.equal(file.sheets[0].rows[0].sku,'001-100');
 const rows=mapRows(file.sheets[0],autoMapping(file.sheets[0].headers,'offers'),{kind:'offers',sourceName:'offers.xlsx',sourceId:file.sourceId});
 assert.equal(rows[0].id,'A');assert.equal(rows[0]._source.row,2);assert.equal(rows[1].price,'9,50');
 await assert.rejects(readExample('rejected-formula.xlsx'),/формулы запрещены/);
 await assert.rejects(readExample('rejected-damaged.xlsx'),/повреждён/);
 for(const value of [{sharedFormula:'A1',result:2},{error:'#DIV/0!'},new Date('2026-01-01')]){
  const w=new ExcelJS.Workbook(),s=w.addWorksheet('bad');s.addRow(['name']);s.addRow([value]);
  if(value.sharedFormula){s.getCell('A1').value={formula:'1+1',result:2};}
  await assert.rejects(readTable(await w.xlsx.writeBuffer(),{name:'bad.xlsx'}));
 }
});
